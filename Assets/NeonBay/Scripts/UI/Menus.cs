        Quest journalSel;

        void DrawJournalTab(Rect area)
        {
            var qs = Game.Quests;
            GUILayout.BeginArea(new Rect(area.x, area.y, 520, area.height));
            scroll = GUILayout.BeginScrollView(scroll);
            GUILayout.Label("ACTIVE", UISkin.header);
