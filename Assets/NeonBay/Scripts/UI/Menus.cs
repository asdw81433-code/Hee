                if (q.status == QuestStatus.Completed && GUILayout.Button("<color=#8899aa>" + q.title + "</color>", journalSel == q ? UISkin.buttonSel : UISkin.button, GUILayout.Height(38))) journalSel = q;
            GUILayout.Space(10);
            GUILayout.Label("DATA SHARDS", UISkin.header);
            for (int i = 0; i < Lore.ShardCount; i++)
                if (Flags.Has("shard_" + i) && GUILayout.Button(Lore.Shard(i).title, UISkin.button, GUILayout.Height(36))) ShowLore(Lore.Shard(i).title, Lore.Shard(i).text);
            GUILayout.EndScrollView();
            GUILayout.EndArea();

            var q2 = journalSel ?? qs.tracked;
            if (q2 == null) return;
            GUILayout.BeginArea(new Rect(area.x + 560, area.y, area.width - 560, area.height), UISkin.panel);
            GUILayout.Label(q2.title.ToUpperInvariant(), UISkin.header);
            GUILayout.Label("Given by " + q2.giver + "   //   " + q2.status + (q2.money > 0 ? "   //   Reward " + Util.Credits(q2.money) : ""), UISkin.labelSmall);
