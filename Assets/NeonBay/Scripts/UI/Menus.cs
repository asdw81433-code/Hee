        // ================================================================== pause menu
        static readonly string[] pauseTabs = { "CHARACTER", "INVENTORY", "CYBERWARE", "JOURNAL", "MAP", "SETTINGS", "SAVE / LOAD" };

        void DrawPause()
        {
            UISkin.Rect(new Rect(0, 0, W, H), new Color(0.0f, 0.01f, 0.02f, 0.82f));
            float tw = (W - 160) / pauseTabs.Length;
            for (int i = 0; i < pauseTabs.Length; i++)
                if (GUI.Button(new Rect(80 + i * tw, 30, tw - 8, 44), pauseTabs[i], i == pauseTab ? UISkin.tabSel : UISkin.tab)) { pauseTab = i; scroll = Vector2.zero; Game.Audio?.Play2D("ui_blip", 0.3f); }
            var area = new Rect(80, 100, W - 160, H - 190);
            switch (pauseTab)
            {
                case 0: DrawCharacterTab(area); break;
                case 1: DrawInventoryTab(area); break;
                case 2: DrawCyberwareTab(area); break;
                case 3: DrawJournalTab(area); break;
                case 4: DrawFullMap(area); break;
                case 5: GUILayout.BeginArea(new Rect(area.x, area.y, 640, area.height)); DrawSettings(); GUILayout.EndArea(); GUILayout.BeginArea(new Rect(area.x + 700, area.y, 640, area.height)); DrawControls(); GUILayout.EndArea(); break;
                case 6: GUILayout.BeginArea(new Rect(area.x, area.y, 760, area.height)); DrawSaveSlots(true); GUILayout.EndArea(); break;
            }
            if (UISkin.Button(new Rect(80, H - 74, 220, 48), "RESUME  [ESC]")) Game.Manager.SetState(GameState.Playing);
            if (UISkin.Button(new Rect(320, H - 74, 260, 48), "QUIT TO MENU")) { Game.Manager.AutoSave(); Game.Manager.QuitToMenu(); }
        }

