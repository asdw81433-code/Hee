            foreach (var slot in all)
            {
                GUILayout.BeginHorizontal(UISkin.box);
                GUILayout.Label("<b>" + slot.ToUpperInvariant() + "</b>\n<size=14>" + SaveSystem.Describe(slot) + "</size>", UISkin.labelSmall, GUILayout.Width(460));
                bool exists = SaveSystem.Exists(slot);
                if (canSave && slot != SaveSystem.Auto && GUILayout.Button("SAVE", UISkin.button, GUILayout.Width(100), GUILayout.Height(48)))
                {
                    if (Game.Manager.SaveTo(slot)) Notify("Saved to " + slot, Palette.Green);
                }
                GUI.enabled = exists;
                if (GUILayout.Button("LOAD", UISkin.button, GUILayout.Width(100), GUILayout.Height(48))) Game.Manager.LoadFrom(slot);
                GUI.enabled = true;
                GUILayout.EndHorizontal();
            }
        }

        // ================================================================== death & ending
        void DrawDeath()
        {
            UISkin.Rect(new Rect(0, 0, W, H), new Color(0.25f, 0f, 0.02f, 0.6f));
            UISkin.Text(new Rect(0, H * 0.3f, W, 90), "FLATLINED", UISkin.title, Palette.Red);
            UISkin.Text(new Rect(0, H * 0.3f + 90, W, 30), "Your vitals hit zero. The city keeps moving without you.", UISkin.center, Color.white);
            if (UISkin.Button(new Rect(W * 0.5f - 200, H * 0.56f, 400, 54), "RESPAWN AT DOC REYES'S  (-10% CASH)")) Game.Manager.RespawnAtClinic();
            string recent = SaveSystem.MostRecent();
            if (recent != null && UISkin.Button(new Rect(W * 0.5f - 200, H * 0.56f + 64, 400, 54), "LOAD LAST SAVE")) Game.Manager.LoadFrom(recent);
            if (UISkin.Button(new Rect(W * 0.5f - 200, H * 0.56f + 128, 400, 54), "QUIT TO MENU")) Game.Manager.QuitToMenu();
        }

        void DrawEnding()
        {
            UISkin.Rect(new Rect(0, 0, W, H), new Color(0, 0, 0, 0.88f));
            var m = Game.Manager;
            UISkin.Text(new Rect(0, 90, W, 70), m.endingTitle, new GUIStyle(UISkin.title) { fontSize = 48 }, UISkin.Accent);
            UISkin.Text(new Rect(W * 0.5f - 560, 190, 1120, 560), m.endingText, new GUIStyle(UISkin.labelBig) { fontSize = 22 }, UISkin.TextColor);
            var s = Game.Stats;
            if (s != null) UISkin.Text(new Rect(0, H - 220, W, 30), "Level " + s.Level + "   //   " + Util.Credits(s.Money) + "   //   Street Cred " + s.StreetCred + "   //   Shards " + Game.Activities.ShardsFound + "/" + Lore.ShardCount + "   //   Play time " + System.TimeSpan.FromSeconds(Game.PlayTime).ToString(@"hh\:mm"), UISkin.center, UISkin.Dim);
            if (UISkin.Button(new Rect(W * 0.5f - 420, H - 150, 400, 54), "CONTINUE IN NEON BAY")) Game.Manager.SetState(GameState.Playing);
            if (UISkin.Button(new Rect(W * 0.5f + 20, H - 150, 400, 54), "MAIN MENU")) Game.Manager.QuitToMenu();
        }
