            GUILayout.Label(q2.summary, UISkin.label);
            GUILayout.Space(10);
            if (q2.status == QuestStatus.Active && q2.Step != null)
            {
                foreach (var o in q2.Step.objectives) if (!string.IsNullOrEmpty(o.text)) GUILayout.Label((o.Done ? "■ " : "□ ") + o.Display, UISkin.label);
                GUILayout.Space(10);
                GUILayout.BeginHorizontal();
                if (q2 != qs.tracked && GUILayout.Button("TRACK", UISkin.button, GUILayout.Width(160), GUILayout.Height(44))) qs.tracked = q2;
                if (q2.kind != QuestKind.Main && GUILayout.Button("ABANDON", UISkin.button, GUILayout.Width(160), GUILayout.Height(44))) { qs.Abandon(q2); journalSel = null; }
                GUILayout.EndHorizontal();
            }
            GUILayout.Space(10);
            foreach (var l in q2.log) GUILayout.Label("- " + l, UISkin.labelSmall);
            GUILayout.EndArea();
        }

