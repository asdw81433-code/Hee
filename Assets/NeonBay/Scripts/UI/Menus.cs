        void DrawInventoryTab(Rect area)
        {
            var inv = Game.Inventory;
            GUILayout.BeginArea(new Rect(area.x, area.y, area.width * 0.55f, area.height));
            GUILayout.Label("WEAPONS  (equip to slots 1-4)", UISkin.header);
            scroll = GUILayout.BeginScrollView(scroll);
            foreach (var w in inv.weapons.ToArray())
            {
                var d = w.Def;
                if (d == null) continue;
                GUILayout.BeginHorizontal(UISkin.box);
                int eq = System.Array.IndexOf(inv.slots, w);
                GUILayout.Label("<color=#" + ColorUtility.ToHtmlStringRGB(w.RarityColor) + "><b>" + w.DisplayName + "</b></color>  <size=13>" + Weapons.RarityName(w.tier) + (eq >= 0 ? "  [SLOT " + (eq + 1) + "]" : "") + "</size>\n<size=13>" + d.desc + "\nDMG " + Mathf.RoundToInt(d.damage * w.DamageMult) + (d.pellets > 1 ? "x" + d.pellets : "") + (d.IsMelee ? "" : "   RPM " + Mathf.RoundToInt(d.fireRate * 60) + "   MAG " + d.mag + "   " + d.ammo) + "</size>", UISkin.labelSmall, GUILayout.Width(area.width * 0.55f - 290));
                for (int i = 0; i < 4; i++)
                    if (GUILayout.Button((i + 1).ToString(), eq == i ? UISkin.tabSel : UISkin.tab, GUILayout.Width(50), GUILayout.Height(50))) inv.Equip(w, i);
                GUILayout.EndHorizontal();
            }
            if (inv.weapons.Count == 0) GUILayout.Label("No weapons. Your fists will have to do.", UISkin.labelSmall);
            GUILayout.EndScrollView();
            GUILayout.EndArea();

            GUILayout.BeginArea(new Rect(area.x + area.width * 0.58f, area.y, area.width * 0.42f, area.height));
            GUILayout.Label("ITEMS", UISkin.header);
            GUILayout.Label("Credits: " + Util.Credits(Game.Stats.Money), UISkin.label);
            foreach (var kv in new System.Collections.Generic.List<System.Collections.Generic.KeyValuePair<string, int>>(inv.AllItems))
            {
                var def = Items.Get(kv.Key);
                if (def == null) continue;
                GUILayout.BeginHorizontal();
                GUILayout.Label("<b>" + def.name + "</b> x" + kv.Value + "\n<size=13>" + def.desc + "</size>", UISkin.labelSmall, GUILayout.Width(area.width * 0.42f - 140));
                if (def.kind == ItemKind.Consumable && GUILayout.Button("USE", UISkin.button, GUILayout.Width(90), GUILayout.Height(40))) inv.Use(kv.Key);
                GUILayout.EndHorizontal();
            }
            GUILayout.EndArea();
        }

